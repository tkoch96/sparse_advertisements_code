"""Regenerate the solver_fork copies from mainline (Tom 2026-08-17).

The fork = mainline file + the MINIMAL imports rewrite routing all
gurobipy access through experiments/solver_fork/gpshim.py and all
intra-fork imports at the fork copies. Every transform must apply
EXACTLY ONCE or this script refuses (a mainline refactor that moves an
import line must be reviewed, not silently mis-forked).

    python -m experiments.solver_fork.regen_fork        # regen + report

Re-run after pulling mainline changes to the five source files.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

SHIM_IMPORT = 'from experiments.solver_fork import gpshim as gp'
ALIAS_IMPORT = ('from experiments.solver_fork import _alias as _solver_fork_alias'
                '  # MUST precede optimal_adv_wrapper (routes its '
                'solve_lp_assignment star-import to the fork)')

# file -> list of (old, new) exact-string transforms, each required once
TRANSFORMS = {
    'solve_lp_assignment.py': [
        ('import gurobipy as gp', SHIM_IMPORT),
    ],
    'path_distribution_computer.py': [
        ('import gurobipy as gp', SHIM_IMPORT),
        ('from optimal_adv_wrapper import Optimal_Adv_Wrapper',
         ALIAS_IMPORT + '\nfrom optimal_adv_wrapper import Optimal_Adv_Wrapper'),
        ('from solve_lp_assignment import',
         'from experiments.solver_fork.solve_lp_assignment import'),
    ],
    'path_distribution_computer_ray.py': [
        ('from path_distribution_computer import',
         'from experiments.solver_fork.path_distribution_computer import'),
        ('from solve_lp_assignment import',
         'from experiments.solver_fork.solve_lp_assignment import'),
    ],
    'worker_comms_ray.py': [
        ('from path_distribution_computer_ray import Path_Distribution_Computer',
         'from experiments.solver_fork.path_distribution_computer_ray '
         'import Path_Distribution_Computer'),
    ],
    'worker_comms.py': [
        ('from worker_comms_ray import *',
         'from experiments.solver_fork.worker_comms_ray import *'),
        ('from worker_comms_ray import Worker_Manager',
         'from experiments.solver_fork.worker_comms_ray import Worker_Manager'),
    ],
}


def git_sha():
    try:
        return subprocess.check_output(
            ['git', 'rev-parse', '--short', 'HEAD'], cwd=ROOT,
            text=True).strip()
    except Exception:
        return 'unknown'


def main():
    sha = git_sha()
    for fname, transforms in TRANSFORMS.items():
        src_path = os.path.join(ROOT, fname)
        with open(src_path) as f:
            src = f.read()
        for old, new in transforms:
            n = src.count(old)
            if n != 1:
                sys.exit('REFUSING: transform target appears {}x (want 1) '
                         'in {}: {!r}'.format(n, fname, old))
            src = src.replace(old, new)
        header = (
            '# SOLVER-FORK COPY of mainline {} (generated by\n'
            '# experiments/solver_fork/regen_fork.py at mainline {}).\n'
            '# Only the import seams differ: gurobipy -> gpshim facade,\n'
            '# sibling modules -> fork copies. DO NOT hand-edit mainline-\n'
            '# derived code here; fix mainline and re-run regen_fork.\n'
        ).format(fname, sha)
        out_path = os.path.join(HERE, fname)
        with open(out_path, 'w') as f:
            f.write(header + src)
        print('forked {} -> {} ({} transforms)'.format(
            fname, os.path.relpath(out_path, ROOT), len(transforms)))
    print('done (mainline {})'.format(sha))


if __name__ == '__main__':
    main()
